set -uo pipefail

FILE="$1"
if [[ ! -f "$FILE" ]]; then echo "ERROR: ファイルが見つかりません: $FILE"; exit 1; fi

# 口コミ(blockquote)内は原文ママで改変できないため、本文のみを対象にする(行番号は保持するため空行で潰す)
# 各種チェックより先に定義する（$BODYを参照するチェックが後段に複数あるため）
BODY=$(awk '/<blockquote/{inbq=1} {if(inbq) print ""; else print} /<\/blockquote>/{inbq=0}' "$FILE")

# === カウンター: 追記式（サブシェル対策・macOS bash 3.x対応） ===
ERR_FILE=$(mktemp)
WARN_FILE=$(mktemp)
: > "$ERR_FILE"
: > "$WARN_FILE"
trap "rm -f $ERR_FILE $WARN_FILE" EXIT

error() {
  echo "ERROR: $1"
  echo "E" >> "$ERR_FILE"
}
warning() {
  echo "WARNING: $1"
  echo "W" >> "$WARN_FILE"
}

echo "=== lint.sh v3.0 ヤマダイ記事チェック ==="
echo "対象: $FILE"
echo ""

# ============================================
# 1. 表記揺れ・冗長表現（カテゴリF）
# ============================================
echo "--- 表記揺れ（口コミ原文=blockquoteは改変禁止のため除外） ---"
for P in "様々" "行なう" "行なっ" "是非" "下さい" "頂く" "頂き" "致します"; do
  echo "$BODY" | grep -n "$P" | while read -r l; do error "変換必須「${P}」: $l"; done || true
done

# ============================================
# 2. AI表現レイヤー2（prohibited-words.md）
# ============================================
echo "--- AI表現 レイヤー2 ---"
for P in "大きな魅力" "充実しています" "ぴったりの" "ぴったりです" "ぴったりな" "への第一歩" "を両立" "の強みです" "魅力のひとつ" "仕上がり" "仕上げられ" "選ばれています" "把握しておけば" "リスクを減らせ" "OKです" "代表です" "代表格" "払拭" "疑問視" "レストラン品質" "手作りした" "手作りの" "候補です" "選択肢に入" "試してほしい" "さまざまなメリット" "多くのメリット"; do
  echo "$BODY" | grep -n "$P" | while read -r l; do error "AI表現「${P}」: $l"; done || true
done

# ============================================
# 3. AI表現レイヤー4（文末・文型定型）
# ============================================
echo "--- AI表現 レイヤー4（文末・文型定型） ---"
for P in "と言えるでしょう" "と言っても過言" "に他なりません" "と考えられます" "と思われます" "と言っても良い" "してみてはいかがでしょう" "しておきましょう" "といいです" "ためです。"; do
  echo "$BODY" | grep -n "$P" | while read -r l; do warning "レイヤー4「${P}」要確認: $l"; done || true
done

# ============================================
# 4. AI表現レイヤー5（導入・結論定型）
# ============================================
echo "--- AI表現 レイヤー5（導入・結論定型） ---"
for P in "本記事" "いかがでしたでしょうか" "いかがでしたか" "参考になれば幸い" "お役に立てれば" "一助となれば" "最後までお読みいただき"; do
  echo "$BODY" | grep -n "$P" | while read -r l; do error "レイヤー5「${P}」: $l"; done || true
done

# ============================================
# 5. AI表現レイヤー6（訴求・推奨）
# ============================================
echo "--- AI表現 レイヤー6（訴求・推奨） ---"
for P in "に最適" "理想的な" "を叶え" "をかなえ" "を実現" "をサポート" "に応えてくれ" "を提供してくれ" "注目を集め" "話題となって" "人気を集め" "高い評価を得" "信頼されて"; do
  echo "$BODY" | grep -n "$P" | while read -r l; do error "レイヤー6「${P}」: $l"; done || true
done

# ============================================
# 6. AI表現レイヤー7-A（抽象形容詞・副詞）
# ============================================
echo "--- AI表現 レイヤー7-A（抽象形容詞） ---"
for P in "多種多様" "さまざまな" "多岐にわたる" "豊富な" "数多くの" "充実した" "快適な" "スムーズ" "円滑な" "シームレス" "的確に" "適切に" "バランスよく" "総合的に"; do
  grep -n "$P" "$FILE" | while read -r l; do warning "レイヤー7-A「${P}」要確認（多用回避）: $l"; done || true
done

# ============================================
# 7. AI表現レイヤー9（比喩・イディオム拡張）
# ============================================
echo "--- AI表現 レイヤー9（比喩・イディオム拡張） ---"
for P in "カギを握る" "決め手となる" "分岐点" "起爆剤" "切り札" "追い風" "後押し" "足がかり" "橋渡し" "足を踏み入れ" "光を当て" "スポットライト" "一石を投じる" "風穴を開け" "道を切り拓" "扉を開く" "地盤を固め" "土台となる"; do
  grep -n "$P" "$FILE" | while read -r l; do warning "レイヤー9「${P}」要確認: $l"; done || true
done

# ============================================
# 8. AI表現レイヤー11（視点・観点常套句）
# ============================================
echo "--- AI表現 レイヤー11（視点・観点） ---"
for P in "という点において" "という観点" "という視点" "の側面から" "の観点から言え" "の立場から見" "を踏まえると"; do
  grep -n "$P" "$FILE" | while read -r l; do warning "レイヤー11「${P}」要確認: $l"; done || true
done

# ============================================
# 9. AI表現レイヤー12（列挙・構造化定型）
# ============================================
echo "--- AI表現 レイヤー12（列挙・構造化） ---"
for P in "以下で詳しく解説" "順に見ていきましょう" "一つずつ見ていき"; do
  grep -n "$P" "$FILE" | while read -r l; do warning "レイヤー12「${P}」要確認: $l"; done || true
done

# ============================================
# 10. AI表現レイヤー14（背中押し・着地フレーズ）
# ============================================
echo "--- AI表現 レイヤー14（背中押し） ---"
for P in "後悔のない選択" "失敗しないために" "賢い選択" "一歩踏み出して" "今こそ" "理想の.*を手に入れ"; do
  echo "$BODY" | grep -nE "$P" | while read -r l; do warning "レイヤー14「${P}」要確認: $l"; done || true
done

# ============================================
# 11. AI臭いナンバリング
# ============================================
echo "--- AI臭いナンバリング ---"
for P in "[0-9]つのポイント" "[0-9]つのメリット" "[0-9]つの注意点" "[0-9]つの特徴" "[0-9]点を" "[0-9]点に"; do
  echo "$BODY" | grep -nE "$P" | while read -r l; do error "AI臭いナンバリング: $l"; done || true
done

# ============================================
# 12. 比喩表現（レイヤー3）
# ============================================
echo "--- 比喩表現 ---"
for P in "跳ね上が" "ふくらむ" "広がる" "広がり" "近づく" "近づけ" "絞られ" "狭まる" "かみ合" "目を向け" "分かれ目" "道が開け" "判断材料" "検討材料" "参考材料" "材料にして" "材料として"; do
  echo "$BODY" | grep -n "$P" | while read -r l; do error "比喩「${P}」: $l"; done || true
done

# 比喩の「絞る」能動形（2026-08-27 Manabuさん指摘。受身の「絞られ」しか登録されておらず素通りしていた）
#   NG: メニューにしぼっています / 回数を絞れば / プランを絞れます（数や範囲を狭める比喩）
#   OK: 〜だけを扱っています / 回数を減らせば / プランを決められます
#   除外: 「体を絞る」（減量の標準語）／「絞り込む」（検索フィルターの操作）／口コミ原文
echo "$BODY" | grep -nE "(絞|しぼ)(る|れ|ろ|っ|り)" | grep -vE "体を(絞|しぼ)|(絞|しぼ)り込" \
  | while read -r l; do warning "比喩の「絞る」（→減らす／少なくする／〜だけにする。※体を絞る・絞り込むは対象外）: $l"; done || true

# 「（金額・条件が）動く」（2026-08-26 Manabuさん指示で追加）
# 金額や条件は物理的に動かないため比喩。「手を動かす」「体を動かす」は物理的な動作なので除外する。
for P in "動く" "動き" "動か"; do
  echo "$BODY" | grep -n "$P" | grep -v "手を動か\|体を動か" | while read -r l; do error "比喩「${P}」（金額・条件は「変わる/変わらない/上がる/下がる」で書く）: $l"; done || true
done

# ============================================
# 13. 後述系（カテゴリB）
# ============================================
# 2026-09-17 拡張：旧版は「後ほど紹介」「前述の通り」「上記で触れ」の完全一致だけで、
#   「後述する」「（後述）」「先ほどの投稿にもあるように」を素通りしていた（まごころケア食 お試し）。
#   公開・制作中の全article.htmlに当てて誤検出0件を確認してから広げた。
#   「上記の」は直前の表を指す正当な用法（らでぃっしゅぼーや 料金 2件）があるため対象外。
echo "$BODY" | grep -nE "先ほど|さきほど|先程|前述|上述|後述|後ほど|のちほど|上記で" | while read -r l; do error "後述系（前後のセクションを指す書き方は禁止・カテゴリB）: $l"; done || true

# ============================================
# 14. 冗長表現（レイヤー1）
# ============================================
echo "--- 冗長表現 ---"
echo "$BODY" | grep -n "という" | while read -r l; do warning "「という」要確認（できれば具体的に）: $l"; done || true
echo "$BODY" | grep -n "といった" | while read -r l; do warning "「といった」要確認（できれば「〜や〜など」に）: $l"; done || true
echo "$BODY" | grep -n "として" | while read -r l; do warning "「として」要確認: $l"; done || true
echo "$BODY" | grep -n "することができます" | while read -r l; do error "冗長「することができます」: $l"; done || true

# ============================================
# 15. 指示語（レイヤー1）
# ============================================
echo "--- 指示語（口コミ除外・ERROR） ---"
# 「きのこの」（鱈ときのこのバター醤油 等の商品名）を誤検出しないよう、きのこ を先に伏せてから判定する（2026-09-17）
echo "$BODY" | sed 's/きのこ/キノコ/g' | grep -n "この" | grep -v "この記事\|この口コミ" | while read -r l; do error "指示語「この」(具体名詞に。例外:この記事では/この口コミ): $l"; done || true
echo "$BODY" | grep -n "その" | grep -v "そのまま\|そのもの\|そのため" | while read -r l; do error "指示語「その」(具体名詞に): $l"; done || true
echo "$BODY" | grep -nE "これ(は|を|が|も)" | grep -v "これまで" | while read -r l; do error "指示語「これ」(具体名詞に): $l"; done || true
echo "$BODY" | grep -n "それ" | grep -v "それぞれ\|それでも\|それなり\|それとも" | while read -r l; do error "指示語「それ」(具体名詞に): $l"; done || true
echo "$BODY" | grep -n "こうした\|そうした" | while read -r l; do error "指示語「こうした/そうした」(具体名詞に): $l"; done || true

# ============================================
# 15b. 無責任系語尾（口コミ除外・ERROR）
# ============================================
echo "--- 無責任系語尾 ---"
for P in "とされています" "とされている" "ようです" "案内されて" "とのことです" "とのこと" "と思われます" "と見られます"; do
  echo "$BODY" | grep -n "$P" | while read -r l; do error "無責任系語尾「${P}」(事実は言い切る): $l"; done || true
done

# ============================================
# 15c. 見出し(H2/H3)内の（）（ERROR）
# ============================================
echo "--- 見出し内の（） ---"
grep -n "<h2>[^<]*（\|<h3>[^<]*（" "$FILE" | while read -r l; do error "見出しに（）: $l"; done || true

# ============================================
# 15d. 強調用「」（WARNING・会話/固有名詞/口コミは誤検出しやすい）
# ============================================
echo "--- 強調用「」 ---"
echo "$BODY" | grep -n "「" | while read -r l; do warning "「」使用（会話・固有名詞以外なら削除）: $l"; done || true

# ============================================
# 15e. 状態語を人の主語・対象にしない（学び49/86・ERROR・口コミ除外）
#   NG: 一人暮らしが選べる / 一人暮らしだと食べきれない / 共働きが増やせる
#   OK: 一人暮らしの人が選べる / 一人暮らしの人だと食べきれない
#   ※「一人暮らしの冷凍庫」のように物を修飾する用法は対象外（「の」が続くため不一致）
#   ※現象を主語にする「一人暮らしが増えています」等は除外
#   2026-08-26 追加: 学び49（2026-07-31 運用反映）が再発したため機械化した
# ============================================
echo "--- 状態語の主語化（学び49/86・口コミ除外） ---"
echo "$BODY" | grep -nE "(一人暮らし|ひとり暮らし|独り暮らし|二人暮らし|ふたり暮らし|共働き|単身赴任|単身世帯|一人世帯)(が|だと)" \
  | grep -vE "(増え|減り|減っ|多く|少なく)" \
  | while read -r l; do error "状態語の主語化（→「〜の人が」「〜の人だと」に）: $l"; done || true

# ============================================
# 15h. 「迷う」（2026-08-27・ERROR・口コミ除外）
#   NG: 申し込みに迷う方も多いです / 価格まわりで迷いやすい点 / 手順に迷いません
#   OK: 申し込みに不安を感じる / 決めかねる / 分かりにくい点 / 手順で困りません
#   ※Manabuさん裁定で **例外なしの全面禁止**（導入文2文目も対象）
#   ※「迷惑」は正当な語のため除外する
# ============================================
echo "--- 「迷う」（ERROR） ---"
echo "$BODY" | grep -n "迷" | grep -v "迷惑" | while read -r l; do error "「迷う」は禁止（→「不安を感じる」「決めかねる」「分かりにくい」など具体的に）: $l"; done || true

# ============================================
# 15j. 「ためらう」（2026-09-17・ERROR・口コミ除外）
#   NG: 申し込みをためらう方もいるのではないでしょうか / 注文をためらってしまう
#   OK: 申し込みに不安を感じる方もいるのではないでしょうか / 申し込むか決めかねる
#   ※Manabuさん指摘（ニチレイ 気くばり御膳 口コミの導入2文目）。漢字表記の「躊躇」も対象
# ============================================
echo "--- 「ためらう」（ERROR） ---"
echo "$BODY" | grep -nE "ためら|躊躇" | while read -r l; do error "「ためらう」は禁止（→「不安を感じる」「決めかねる」など、何が引っかかっているかを書く）: $l"; done || true

# ============================================
